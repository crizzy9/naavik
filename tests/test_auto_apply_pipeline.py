"""Auto-apply honest-pipeline semantics (UX-quality session).

The queue used to be a silent dead-end. Pins the new contract:
- queued jobs with missing docs get them GENERATED by the cron;
- auto-apply OFF → docs prepared + handed to the user (READY_TO_SUBMIT),
  never a silent skip;
- boards without a real submit adapter → READY_TO_SUBMIT with a reason;
- dry-run stamps + hands over instead of re-stamping forever;
- submission failure hands over with the failure message;
- auto_apply_phase computes the UI chip for every pipeline stage.
"""

from __future__ import annotations

from datetime import UTC, datetime
from types import SimpleNamespace
from unittest.mock import AsyncMock, patch

import pytest

from models import ApplicationBoard, ApplicationStatus, DocsState, JobQueueState
from services.application_service import (
    AutoApplyResult,
    auto_apply_phase,
    process_auto_apply_queue,
)
from services.ats import board_supports_auto_submit

# Reuse the canonical fakes from the application-service suite.
from tests.test_application_service import (
    _exec_all,
    _exec_count,
    _exec_one,
    _FakeSession,
    _make_app,
    _make_job,
)


def _settings(**kw):
    base = {
        "user_id": 1,
        "auto_apply_enabled": True,
        "auto_apply_daily_cap": None,
        "auto_apply_score_threshold": 0.7,
        "auto_apply_per_board_daily_caps": {},
        "auto_apply_dry_run": False,
    }
    base.update(kw)
    return SimpleNamespace(**base)


def test_supported_boards_are_the_three_http_adapters():
    assert board_supports_auto_submit(ApplicationBoard.GREENHOUSE)
    assert board_supports_auto_submit(ApplicationBoard.LEVER)
    assert board_supports_auto_submit(ApplicationBoard.ASHBY)
    for board in (
        ApplicationBoard.LINKEDIN,
        ApplicationBoard.INDEED,
        ApplicationBoard.WORKDAY,
        ApplicationBoard.COMPANY_DIRECT,
        ApplicationBoard.MANUAL,
    ):
        assert not board_supports_auto_submit(board)
    assert not board_supports_auto_submit(None)


@pytest.mark.asyncio
async def test_queue_generates_docs_when_missing():
    """docs_state NONE → the cron generates the bundle instead of skipping."""
    app_row = _make_app(docs_state=DocsState.NONE)
    job_row = _make_job(queue_state=JobQueueState.QUEUED_FOR_AUTO_APPLY, score=0.9)
    session = _FakeSession()
    session.exec_queue = [_exec_all([(app_row, job_row)]), _exec_one(_settings())]

    async def fake_generate(sess, application, *, settings, job=None):
        application.docs_state = DocsState.READY
        return SimpleNamespace(skipped_reason=None, degraded=False)

    fake_submit = AsyncMock(
        return_value=_make_app(status=ApplicationStatus.APPLIED, applied_at=datetime.now(UTC))
    )
    with (
        patch("services.generation.generate_bundle", new=fake_generate),
        patch("services.application_service.submit_draft", new=fake_submit),
    ):
        result = await process_auto_apply_queue(session)

    assert result.docs_generated == 1
    assert result.submitted == 1
    blob = (app_row.submission_artifacts or {}).get("auto_apply") or {}
    assert blob.get("docs_ready_at")


@pytest.mark.asyncio
async def test_disabled_hands_docs_ready_job_to_user():
    """auto_apply_enabled=False no longer silently skips — the job flips to
    READY_TO_SUBMIT with a reason."""
    app_row = _make_app(docs_state=DocsState.READY)
    job_row = _make_job(queue_state=JobQueueState.QUEUED_FOR_AUTO_APPLY, score=0.9)
    session = _FakeSession()
    session.exec_queue = [
        _exec_all([(app_row, job_row)]),
        _exec_one(_settings(auto_apply_enabled=False)),
    ]
    result = await process_auto_apply_queue(session)
    assert result.handed_to_user == 1
    assert job_row.queue_state == JobQueueState.READY_TO_SUBMIT
    blob = (app_row.submission_artifacts or {}).get("auto_apply") or {}
    assert "auto-apply is off" in (blob.get("needs_you_reason") or "")



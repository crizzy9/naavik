@pytest.mark.asyncio
async def test_dry_run_hands_over_instead_of_requeueing_forever():
    app_row = _make_app(docs_state=DocsState.READY)
    job_row = _make_job(queue_state=JobQueueState.QUEUED_FOR_AUTO_APPLY, score=0.9)
    session = _FakeSession()
    session.exec_queue = [
        _exec_all([(app_row, job_row)]),
        _exec_one(_settings(auto_apply_dry_run=True)),
        _exec_count(0),  # validate: screener count
        _exec_one(None),  # validate: sponsorship profile
    ]
    # Item 7: dry-run now calls submit_draft(dry_run=True) for real
    # filled-form evidence; the stamp happens inside submit_draft (mocked
    # here), and the hand-off still fires afterwards.
    fake_submit = AsyncMock(return_value=app_row)
    with patch("services.application_service.submit_draft", new=fake_submit):
        result = await process_auto_apply_queue(session)
    fake_submit.assert_awaited_once()
    assert fake_submit.await_args.kwargs.get("dry_run") is True
    assert result.handed_to_user == 1
    assert job_row.queue_state == JobQueueState.READY_TO_SUBMIT


@pytest.mark.asyncio
async def test_submission_failure_hands_over_with_message():
    app_row = _make_app(
        docs_state=DocsState.READY,
        submission_artifacts={"last_failure": {"kind": "captcha", "message": "CAPTCHA wall"}},
    )
    job_row = _make_job(queue_state=JobQueueState.QUEUED_FOR_AUTO_APPLY, score=0.9)
    session = _FakeSession()
    session.exec_queue = [
        _exec_all([(app_row, job_row)]),
        _exec_one(_settings()),
        _exec_count(0),
        _exec_one(None),
    ]
    # submit_draft returns the app still in DRAFT (failure path).
    fake_submit = AsyncMock(return_value=app_row)
    with patch("services.application_service.submit_draft", new=fake_submit):
        result = await process_auto_apply_queue(session)
    assert result.failed == 1
    assert result.handed_to_user == 1
    assert job_row.queue_state == JobQueueState.READY_TO_SUBMIT
    blob = (app_row.submission_artifacts or {}).get("auto_apply") or {}
    assert "CAPTCHA wall" in (blob.get("needs_you_reason") or "")


def test_auto_apply_phase_covers_the_pipeline():
    job_q = _make_job(queue_state=JobQueueState.QUEUED_FOR_AUTO_APPLY)
    assert auto_apply_phase(_make_app(docs_state=DocsState.GENERATING), job_q)["phase"] == (
        "generating"
    )
    assert auto_apply_phase(_make_app(docs_state=DocsState.READY), job_q)["phase"] == "docs_ready"
    assert auto_apply_phase(_make_app(docs_state=DocsState.NONE), job_q)["phase"] == "queued"

    job_ready = _make_job(queue_state=JobQueueState.READY_TO_SUBMIT)
    app_ready = _make_app(
        docs_state=DocsState.READY,
        submission_artifacts={"auto_apply": {"needs_you_reason": "no adapter"}},
    )
    phase = auto_apply_phase(app_ready, job_ready)
    assert phase["phase"] == "needs_you"
    assert phase["reason"] == "no adapter"

    job_applied = _make_job(queue_state=JobQueueState.APPLIED)
    app_applied = _make_app(status=ApplicationStatus.APPLIED, applied_at=datetime.now(UTC))
    assert auto_apply_phase(app_applied, job_applied)["phase"] == "submitted"

    assert auto_apply_phase(None, job_q) is None
    assert auto_apply_phase(_make_app(), _make_job(queue_state=JobQueueState.UNSWIPED)) is None


